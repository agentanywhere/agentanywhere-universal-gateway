#!/usr/bin/env python3
"""Generate docs/reference/http-endpoints.md from the application's routes.

The page lists every HTTP and WebSocket operation the gateway registers, with
the credential it needs, its parameters and the first line of its docstring.
It is built by importing ``app.main`` and reading FastAPI's route table and
OpenAPI schema, so it needs the project's dependencies installed
(``pip install -r requirements.txt``). It does not start a server and does not
open the database.

Usage::

    python scripts/generate_http_reference.py           # rewrite the page
    python scripts/generate_http_reference.py --check   # exit 1 if it is stale

Do not edit the generated page by hand; change this script or the code and
run it again.
"""
from __future__ import annotations

import argparse
import os
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "reference" / "http-endpoints.md"

# Importing app.main reads settings. Use fixed, harmless values so the output
# does not depend on the caller's .env or environment.
os.environ.setdefault("SECRET_KEY", "docs-generator-not-a-real-secret")
os.environ.setdefault("DATABASE_URL", "sqlite+aiosqlite:///:memory:")
os.environ.setdefault("REDIS_ENABLED", "false")
os.environ.setdefault("LOG_LEVEL", "CRITICAL")
# These change which routes exist, so pin them to the shipped defaults.
os.environ["HEALTH_CHECK_PATH"] = "/health"
os.environ["METRICS_PATH"] = "/metrics"
os.environ["DEBUG"] = "false"
for _name in ("MQTT_BROKER_URL", "GRPC_BACKEND_URL", "WEBSOCKET_BACKEND_URL", "GRAPHQL_BACKEND_URL"):
    os.environ.pop(_name, None)

sys.path.insert(0, str(ROOT))

HEADER = """# HTTP endpoints (generated)

<!-- Generated by scripts/generate_http_reference.py. Do not edit by hand. -->

This page is generated from the gateway's route table. It lists every
operation, the credential it needs and its parameters. For conventions,
examples and real responses, read the [HTTP API reference](http-api.md).

Credential column:

- **admin**: the admin credential (`Authorization: Bearer <ADMIN_TOKEN>`; see
  the [security model](../explanation/security-model.md)).
- **admin (query or header)**: the admin credential as `?token=` or as a bearer
  header.
- **none**: no credential.
- **API key**: an API key in `X-API-Key` or `Authorization: Bearer`.

Parameter notation: `name` is required, `name?` is optional, `=value` is the
default. *query*, *path* and *body* say where the parameter goes.
"""

PUBLIC_DATA_PLANE = {
    "/health", "/metrics", "/ready", "/live", "/health/detailed",
    "/docs", "/redoc", "/openapi.json",
    "/.well-known/agent-card.json", "/.well-known/ag-ui.json",
}


def _deps(dependant, acc):
    for dep in dependant.dependencies:
        acc.add(getattr(dep.call, "__name__", str(dep.call)))
        _deps(dep, acc)
    return acc


def _type_name(annotation) -> str:
    """A short, version-independent name for a parameter's type."""
    import typing

    origin = typing.get_origin(annotation)
    args = [a for a in typing.get_args(annotation) if a is not type(None)]
    if origin is typing.Union and args:
        return _type_name(args[0])
    if origin in (list, tuple, set) or annotation in (list, tuple, set):
        return "array"
    if origin is dict or annotation is dict:
        return "object"
    if isinstance(annotation, type):
        try:
            from pydantic import BaseModel

            if issubclass(annotation, BaseModel):
                return f"`{annotation.__name__}`"
        except Exception:  # pragma: no cover - defensive
            pass
        return {str: "string", int: "integer", float: "number", bool: "boolean"}.get(annotation, "value")
    return "value"


def _fmt_default(field) -> str:
    if getattr(field, "required", True):
        return ""
    default = getattr(field, "default", None)
    if default is None or default == "" or repr(default) == "PydanticUndefined":
        return ""
    return f"={default}"


def _param_name(field) -> str:
    return (getattr(field, "alias", None) or field.name) + ("" if field.required else "?")


def _params(route) -> str:
    """Describe a route's parameters from FastAPI's dependency tree.

    Reading the dependant (rather than the OpenAPI schema) keeps the output
    the same across the FastAPI and pydantic versions CI and developers use.
    """
    from fastapi.dependencies.utils import get_flat_dependant

    flat = get_flat_dependant(route.dependant, skip_repeats=True)
    out = []
    for field in flat.path_params:
        out.append(f"`{_param_name(field)}` *path*")
    for field in flat.query_params:
        out.append(f"`{_param_name(field)}` *query*{_fmt_default(field)}")
    body = list(flat.body_params)
    if len(body) == 1 and not getattr(body[0].field_info, "embed", False):
        out.append(f"JSON body: {_type_name(body[0].field_info.annotation)}")
    else:
        for field in body:
            out.append(f"`{_param_name(field)}` *body*{_fmt_default(field)}")
    return "<br>".join(out)


def _summary(endpoint):
    """First paragraph of the endpoint's docstring, on one line."""
    lines = []
    for raw in (endpoint.__doc__ or "").strip().splitlines():
        if not raw.strip():
            break
        lines.append(raw.strip())
    text = " ".join(lines)
    return text.replace("|", "\\|").replace("``", "`")


def _section(path):
    if path.startswith("/admin/"):
        seg = path.split("/")[2]
        return f"Admin: /admin/{seg}"
    if path.startswith("/oauth2"):
        return "OAuth2"
    if path in PUBLIC_DATA_PLANE or path.startswith("/.well-known"):
        return "Health, metrics and discovery"
    return "Data plane"


def build() -> str:
    warnings.simplefilter("ignore")
    from fastapi.routing import APIRoute, APIWebSocketRoute

    import contextlib
    import io

    # Importing the app logs start-up lines to stdout; keep them out of the way.
    with contextlib.redirect_stdout(io.StringIO()):
        from app.main import app

    rows = {}
    op_count = [0]
    for route in app.routes:
        if isinstance(route, APIRoute):
            deps = _deps(route.dependant, set())
            path = route.path
            if "verify_admin_token" in deps:
                auth = "admin"
            elif path == "/admin/agents/stream":
                auth = "admin (query or header)"
            elif path.startswith("/admin") or path.startswith("/oauth2") or path in PUBLIC_DATA_PLANE:
                auth = "none"
            else:
                auth = "API key"
            methods = sorted(route.methods)
            params = _params(route)
            if path == "/{path:path}":
                auth = "API key (none for OPTIONS)"
            rows.setdefault(_section(path), []).append(
                (path, ", ".join(methods), auth, params, _summary(route.endpoint))
            )
            op_count[0] += len(methods)
        elif getattr(route, "path", None) == "/openapi.json":
            rows.setdefault(_section("/openapi.json"), []).append(
                ("/openapi.json", "GET, HEAD", "none", "", "OpenAPI schema, served by FastAPI.")
            )
            op_count[0] += 2
        elif isinstance(route, APIWebSocketRoute):
            rows.setdefault("WebSocket", []).append(
                (route.path, "WS", "see note", "", _summary(route.endpoint))
            )
            op_count[0] += 1

    order = ["Health, metrics and discovery", "Data plane", "WebSocket", "OAuth2"]
    order += sorted(k for k in rows if k.startswith("Admin"))
    total = op_count[0]
    admin_total = sum(len(r[1].split(", ")) for k, v in rows.items() if k.startswith("Admin") for r in v)
    admin_open = sum(1 for k, v in rows.items() if k.startswith("Admin") for r in v if r[2] == "none")

    lines = [HEADER.rstrip(), ""]
    lines.append(
        f"Totals: {total} operations (one per method and path), of which "
        f"{admin_total} are under `/admin`. {admin_open} admin operations need "
        "no credential."
    )
    lines.append("")
    lines.append("## Contents")
    lines.append("")
    for name in order:
        if name in rows:
            anchor = _anchor(name)
            lines.append(f"- [{name}](#{anchor}) ({len(rows[name])})")
    lines.append("")
    for name in order:
        if name not in rows:
            continue
        lines.append(f"## {name}")
        lines.append("")
        if name == "WebSocket":
            lines.append(
                "The HTTP authentication middleware does not run for WebSocket "
                "connections. `/ws/{path}` checks an API key itself and, as shipped, "
                "closes every connection (see the "
                "[protocol support matrix](../explanation/protocol-support.md)). "
                "`/agents/{full_path}` is the agent edge and applies no gateway "
                "credential."
            )
            lines.append("")
        lines.append("| Method | Path | Credential | Parameters | Summary |")
        lines.append("|---|---|---|---|---|")
        for path, method, auth, params, summary in rows[name]:
            lines.append(f"| {method} | `{path}` | {auth} | {params} | {summary} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _anchor(title: str) -> str:
    import re

    a = title.strip().lower()
    a = re.sub(r"[^\w\- ]", "", a)
    return a.replace(" ", "-")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the page is out of date")
    args = parser.parse_args()
    content = build()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date. Run: python scripts/generate_http_reference.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
